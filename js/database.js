/* =========================================================
   中山韵典 · 数据解析
   数据格式：标记行 [汉字] [拼音] [释义] [例句] [词条] ...
   ========================================================= */

window.parseDialectDatabase = function (text) {
    const entries = [];
    const lines = String(text || '').split('\n');

    let entry = null;
    let py = null;

    const isTopMarker = (l) => /^\[(汉字|拼音|释义|例句|词条|注意)/.test(l);

    for (let i = 0; i < lines.length; i++) {
        const raw = lines[i].trim();
        if (!raw) continue;

        /* ---- 新字头 ---- */
        if (raw.startsWith('[汉字]')) {
            if (entry) {
                if (py) entry.pinyins.push(py);
                entries.push(entry);
            }
            py = null;
            const val = raw.slice(4);
            entry = {
                character: val.startsWith('IMG:')
                    ? { type: 'img', src: val.slice(4) }
                    : val,
                pinyins: []
            };
            continue;
        }

        if (!entry) continue;

        /* ---- 新拼音 ---- */
        if (raw.startsWith('[拼音]')) {
            if (py) entry.pinyins.push(py);
            py = { pinyin: raw.slice(4), meanings: [], entries: [], notes: null };
            continue;
        }

        if (!py) continue;

        /* ---- 释义 ---- */
        if (raw.startsWith('[释义')) {
            py.meanings.push({
                text: raw.slice(raw.indexOf(']') + 1),
                examples: []
            });
            continue;
        }

        /* ---- 例句（归属最后一条释义） ---- */
        if (raw.startsWith('[例句]')) {
            let translation = '';
            if (i + 1 < lines.length && lines[i + 1].trim().startsWith('[例句翻译]')) {
                translation = lines[i + 1].trim().slice(6);
                i++;
            }
            const ex = { dialect: raw.slice(4), translation };
            const last = py.meanings[py.meanings.length - 1];
            if (last) last.examples.push(ex);
            else py.meanings.push({ text: '', examples: [ex] });
            continue;
        }

        /* ---- 词条 ---- */
        if (raw.startsWith('[词条]')) {
            const item = { title: raw.slice(4), examples: [] };
            let j = i + 1;

            for (; j < lines.length; j++) {
                const l = lines[j].trim();
                if (!l) continue;

                if (l.startsWith('[词条拼音]')) {
                    item.entryPinyin = l.slice(6);
                } else if (l.startsWith('[词条释义]')) {
                    item.definition = l.slice(6);
                } else if (l.startsWith('[词条例句]')) {
                    let t = '';
                    if (j + 1 < lines.length && lines[j + 1].trim().startsWith('[词条例句翻译]')) {
                        t = lines[j + 1].trim().slice(8);
                        j++;
                    }
                    item.examples.push({ dialect: l.slice(6), translation: t });
                } else if (isTopMarker(l)) {
                    break;
                }
            }

            py.entries.push(item);
            i = j - 1;
            continue;
        }

        /* ---- 注意 ---- */
        if (raw.startsWith('[注意]')) {
            py.notes = raw.slice(4);
            continue;
        }
    }

    if (entry) {
        if (py) entry.pinyins.push(py);
        entries.push(entry);
    }

    return entries;
};